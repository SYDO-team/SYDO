#ifndef SYDO_SIGNATURE_H
#define SYDO_SIGNATURE_H

#include "parameters.h"

enum {
    SIGNATURE_UHASH = SYDO_CORRECTIONS_BYTES,
    SIGNATURE_WITNESS = SIGNATURE_UHASH + SYDO_VOLE_HASH_BYTES,
    SIGNATURE_PROOF = SIGNATURE_WITNESS + SYDO_WITNESS_BYTES,
    SIGNATURE_OPENING = SIGNATURE_PROOF + SYDO_PROOF_BYTES,
    SIGNATURE_CHALLENGE = SIGNATURE_OPENING + SYDO_OPEN_BYTES,
    SIGNATURE_IV = SIGNATURE_CHALLENGE + SYDO_SEED_BYTES,
    SIGNATURE_COUNTER = SIGNATURE_IV + SYDO_SEED_BYTES
};

_Static_assert(SIGNATURE_COUNTER + 4 == SYDO_SIG_BYTES, "signature encoding length");

#endif
